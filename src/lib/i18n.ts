/** Interface languages for the dashboard. English is the default. */
export interface LanguageDef {
  code: string;
  /** Native label shown in the picker. */
  label: string;
  /** English name, also sent to the AI so replies match. */
  english: string;
  dir: 'ltr' | 'rtl';
  flag: string;
}

export const LANGUAGES: LanguageDef[] = [
  { code: 'en', label: 'English', english: 'English', dir: 'ltr', flag: '🇬🇧' },
  { code: 'ur', label: 'اردو', english: 'Urdu', dir: 'rtl', flag: '🇵🇰' },
  { code: 'roman', label: 'Roman Urdu', english: 'Roman Urdu (Urdu written in Latin script)', dir: 'ltr', flag: '🇵🇰' },
  { code: 'ar', label: 'العربية', english: 'Arabic', dir: 'rtl', flag: '🇸🇦' },
  { code: 'hi', label: 'हिन्दी', english: 'Hindi', dir: 'ltr', flag: '🇮🇳' },
  { code: 'zh', label: '中文', english: 'Chinese (Simplified)', dir: 'ltr', flag: '🇨🇳' },
  { code: 'es', label: 'Español', english: 'Spanish', dir: 'ltr', flag: '🇪🇸' },
  { code: 'fr', label: 'Français', english: 'French', dir: 'ltr', flag: '🇫🇷' },
  { code: 'ps', label: 'پښتو', english: 'Pashto', dir: 'rtl', flag: '🇦🇫' },
  { code: 'bn', label: 'বাংলা', english: 'Bengali', dir: 'ltr', flag: '🇧🇩' },
];

export function languageDef(code: string | null | undefined): LanguageDef {
  return LANGUAGES.find((l) => l.code === code) ?? LANGUAGES[0]!;
}

